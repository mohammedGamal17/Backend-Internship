--- Display all products with their categories and suppliers.----
SELECT p.ProductID,p.Name AS ProductName,
        c.CategoryName,
        u.FirstName + N' ' + u.LastName AS SupplierName,
        p.UnitPrice,
        p.IsActive
FROM Products p
LEFT JOIN  Categories c ON c.CategoryID = p.CategoryID
LEFT JOIN  Suppliers  s ON s.SupplierID = p.SupplierID
LEFT JOIN  Users      u ON u.UserID = s.SupplierID
ORDER BY c.CategoryName, p.Name;
GO

-----Find the top five best-selling products.-----
SELECT TOP (5) WITH TIES
        p.ProductID,
        p.Name AS ProductName,
        SUM(oi.Quantity) AS UnitsSold,
        SUM(oi.Quantity * oi.UnitPrice) AS Revenue
FROM    OrderItems oi
JOIN    Orders o ON o.OrderID = oi.OrderID
JOIN     Products p ON p.ProductID = oi.ProductID
WHERE   o.IsCancelled = 0
GROUP BY p.ProductID, p.Name
ORDER BY UnitsSold DESC;
GO

-----Calculate total sales for each month.-----
SELECT  YEAR(o.OrderDate) AS SalesYear,
        MONTH(o.OrderDate) AS SalesMonth,
        COUNT(DISTINCT o.OrderID) AS OrderCount,
        SUM(oi.Quantity) AS UnitsSold,
        SUM(oi.Quantity * oi.UnitPrice)  AS TotalSales
FROM     Orders o
JOIN     OrderItems oi ON oi.OrderID = o.OrderID
WHERE   o.IsCancelled = 0
GROUP BY YEAR(o.OrderDate), MONTH(o.OrderDate)
ORDER BY SalesYear, SalesMonth;
GO


-------Find customers who have never placed an order--------
SELECT c.CustomerID,
        u.FirstName + N' ' + u.LastName  AS CustomerName,
        u.JoinedAt
From Customers c
JOIN Users u on u.UserID = c.CustomerID
JOIN Orders o on c.CustomerID = o.CustomerID
WHERE   NOT EXISTS (SELECT 1 FROM dbo.Orders o WHERE o.CustomerID = c.CustomerID)
ORDER BY c.CustomerID;
GO

------- Find products that have never been sold.---------
SELECT p.ProductID,
       p.Name AS ProductName,
       c.CategoryName,
       p.UnitPrice,
       p.IsActive
FROM Products p
JOIN    dbo.Categories c ON c.CategoryID = p.CategoryID
WHERE NOT EXISTS (SELECT 1 FROM OrderItems oi WHERE oi.ProductID = p.ProductID)
ORDER BY p.ProductID


------Display customers whose total purchases exceed a specified amount------

DECLARE @MinAmount DECIMAL(12,2) = 1200;

SELECT c.CustomerID,
       u.FirstName + N' ' + u.LastName AS CustomerName,
       dbo.GetCustomerTotalPurchases(c.CustomerID) AS TotalPurchases,
       u.JoinedAt
FROM Customers c
JOIN Users u ON u.UserID=c.CustomerID
WHERE dbo.GetCustomerTotalPurchases(c.CustomerID) > @MinAmount;


-------- Find products whose available stock is below a specified threshold------

DECLARE @Threshold INT =5.

SELECT p.ProductID,
       p.Name AS ProductName,
       c.CategoryName,
       p.IsActive,
       dbo.GetProductAvailableStock(p.ProductID) AS AvailableStock,
       p.UnitPrice
FROM Products p
LEFT JOIN Categories c ON c.CategoryID = p.CategoryID
WHERE dbo.GetProductAvailableStock(p.ProductID) < @Threshold;


------- Calculate the total revenue generated by each category-------


SELECT c.CategoryID,
       c.CategoryName,
       COUNT(DISTINCT p.ProductID) AS Products
FROM Categories c
LEFT JOIN Products p ON p.CategoryID = c.CategoryID
LEFT JOIN
(
    SELECT oi.ProductID, SUM(oi.Quantity * oi.UnitPrice) AS Revenue
    FROM   OrderItems oi
    JOIN   Orders o ON o.OrderID = oi.OrderID
    WHERE  o.IsCancelled = 0
    GROUP BY oi.ProductID
) r ON r.ProductID = p.ProductID
GROUP BY c.CategoryID, c.CategoryName
GO
